#!/usr/bin/env python3
"""
Harden and verify the `securepam` realm on a (new) AWS Keycloak. Idempotent; safe to re-run.

    KEYCLOAK_ADMIN_USER=<bootstrap admin> python3 configure-realm.py \
        --url https://auth.ops.example.com --frontend-url https://securepam.ops.example.com \
        --secret-arn <terraform output audit_reader_secret_arn>

The admin password is read from a hidden prompt (or KEYCLOAK_ADMIN_PASSWORD); the audit-reader secret
is generated by Keycloak, stored ONLY in Secrets Manager (value via a 0600 temp file + file://) or a
0600 file (--secret-out), and never printed. Output is PASS/FAIL lines without secret values.

It never deletes or re-imports a realm, never touches users, and never imports a user export.
"""

import argparse
import getpass
import json
import os
import subprocess
import sys
import tempfile
from typing import List
from urllib.parse import quote

import httpx

REALM = "securepam"
READER = "securepam-audit-reader"
APP = "securepam-app"
LISTENER = "securepam-otp-audit"
REQUIRED_EVENTS = {"LOGIN", "LOGIN_ERROR", "UPDATE_TOTP", "REMOVE_TOTP"}
results: List[tuple] = []


def check(name: str, ok: bool, detail: str = "") -> bool:
    results.append((ok, name, detail))
    print(f"{'PASS' if ok else 'FAIL'} {name}" + (f" - {detail}" if detail else ""))
    return ok


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--url", required=True, help="Keycloak base URL (https://..., or http://localhost:8080 over an SSM port-forward)")
    ap.add_argument("--frontend-url", required=True, help="SecurePAM frontend origin, e.g. https://securepam.ops.example.com")
    ap.add_argument("--ssl-required", choices=["all", "external"], default="all")
    ap.add_argument("--secret-arn", default="", help="Secrets Manager secret for the audit-reader client secret")
    ap.add_argument("--secret-out", default="", help="Alternatively write the secret to this 0600 file")
    ap.add_argument("--no-rotate", action="store_true", help="Verify only; do not regenerate the audit-reader secret")
    ap.add_argument("--ca-cert", default=None)
    args = ap.parse_args()
    if not args.no_rotate and not (args.secret_arn or args.secret_out):
        print("FAIL secret destination - pass --secret-arn or --secret-out (the new secret is never printed)")
        return 2

    user = os.environ.get("KEYCLOAK_ADMIN_USER") or input("Keycloak admin username: ").strip()
    password = os.environ.get("KEYCLOAK_ADMIN_PASSWORD") or getpass.getpass("Keycloak admin password (input hidden): ")
    base = args.url.rstrip("/")
    c = httpx.Client(base_url=base, timeout=20, verify=args.ca_cert or True, follow_redirects=False, trust_env=False)
    tok = c.post("/realms/master/protocol/openid-connect/token",
                 data={"grant_type": "password", "client_id": "admin-cli", "username": user, "password": password})
    del password
    if not check("administrator sign-in", tok.status_code == 200, f"HTTP {tok.status_code}"):
        return 1
    H = {"Authorization": f"Bearer {tok.json()['access_token']}"}
    R = f"/admin/realms/{REALM}"

    realm = c.get(R, headers=H)
    if not check(f"realm {REALM} exists (first-boot import)", realm.status_code == 200, f"HTTP {realm.status_code}"):
        return 1
    rep = realm.json()

    # 1. Event listener + persisted events (what the backend MFA sync reads)
    ev = c.get(f"{R}/events/config", headers=H).json()
    listeners = sorted(set(ev.get("eventsListeners") or []) | {LISTENER, "jboss-logging"})
    types = sorted(set(ev.get("enabledEventTypes") or []) | REQUIRED_EVENTS)
    want = {"eventsEnabled": True, "eventsListeners": listeners, "enabledEventTypes": types,
            "eventsExpiration": ev.get("eventsExpiration") or 30 * 24 * 3600}
    if (ev.get("eventsEnabled") is not True or sorted(ev.get("eventsListeners") or []) != listeners
            or sorted(ev.get("enabledEventTypes") or []) != types):
        c.put(f"{R}/events/config", headers=H, json={**ev, **want})
    ev = c.get(f"{R}/events/config", headers=H).json()
    check("event listener securepam-otp-audit + event storage + LOGIN_ERROR",
          LISTENER in ev.get("eventsListeners", []) and ev.get("eventsEnabled") is True
          and "LOGIN_ERROR" in ev.get("enabledEventTypes", []))

    # 2. Realm security: TLS, brute force, TOTP policy, enrolment required for every new user
    patch = {"sslRequired": args.ssl_required, "bruteForceProtected": True, "failureFactor": 5,
             "waitIncrementSeconds": 60, "maxFailureWaitSeconds": 900, "permanentLockout": False,
             "otpPolicyType": "totp", "otpPolicyAlgorithm": "HmacSHA1", "otpPolicyDigits": 6,
             "otpPolicyPeriod": 30, "otpPolicyCodeReusable": False}
    if any(rep.get(k) != v for k, v in patch.items()):
        r = c.put(R, headers=H, json={**rep, **patch})
        check("realm security settings updated", r.status_code in (200, 204), f"HTTP {r.status_code}")
    rep = c.get(R, headers=H).json()
    check(f"sslRequired={args.ssl_required}, brute-force protection on", rep.get("sslRequired") == args.ssl_required
          and rep.get("bruteForceProtected") is True)
    check("TOTP policy is authenticator-app compatible (TOTP, SHA1, 6 digits, 30 s, no reuse)",
          all(rep.get(k) == patch[k] for k in ("otpPolicyType", "otpPolicyAlgorithm", "otpPolicyDigits", "otpPolicyPeriod", "otpPolicyCodeReusable")))
    ra = c.get(f"{R}/authentication/required-actions/CONFIGURE_TOTP", headers=H).json()
    if not (ra.get("enabled") and ra.get("defaultAction")):
        c.put(f"{R}/authentication/required-actions/CONFIGURE_TOTP", headers=H, json={**ra, "enabled": True, "defaultAction": True})
        ra = c.get(f"{R}/authentication/required-actions/CONFIGURE_TOTP", headers=H).json()
    check("TOTP enrolment is required for every new user (CONFIGURE_TOTP default action)",
          bool(ra.get("enabled") and ra.get("defaultAction")))
    flow = rep.get("browserFlow", "browser")
    execs = c.get(f"{R}/authentication/flows/{quote(flow, safe='')}/executions", headers=H).json()
    otp = [e for e in execs if e.get("providerId") == "auth-otp-form"]
    check(f"browser flow '{flow}' contains the OTP form", bool(otp) and otp[0].get("requirement") in ("REQUIRED", "CONDITIONAL"),
          f"requirement={otp[0].get('requirement') if otp else None}")

    # 3. SecurePAM SPA client: exact redirect, PKCE S256, no password grant
    app = c.get(f"{R}/clients", headers=H, params={"clientId": APP}).json()
    if check(f"client {APP} exists", bool(app)):
        a = app[0]
        front = args.frontend_url.rstrip("/")
        desired = {"redirectUris": [f"{front}/*"], "webOrigins": [front], "publicClient": True,
                   "standardFlowEnabled": True, "directAccessGrantsEnabled": False, "implicitFlowEnabled": False}
        attrs = {**(a.get("attributes") or {}), "pkce.code.challenge.method": "S256", "post.logout.redirect.uris": f"{front}/*"}
        if any(a.get(k) != v for k, v in desired.items()) or (a.get("attributes") or {}).get("pkce.code.challenge.method") != "S256":
            c.put(f"{R}/clients/{a['id']}", headers=H, json={**a, **desired, "attributes": attrs})
        a = c.get(f"{R}/clients/{a['id']}", headers=H).json()
        check(f"{APP}: redirect {front}/*, PKCE S256, no password grant",
              a.get("redirectUris") == [f"{front}/*"] and a.get("attributes", {}).get("pkce.code.challenge.method") == "S256"
              and a.get("directAccessGrantsEnabled") is False)

    # 4. Audit reader: least privilege, fresh secret, proven with its own token
    rd = c.get(f"{R}/clients", headers=H, params={"clientId": READER}).json()
    if not check(f"client {READER} exists", bool(rd)):
        return 1
    rid = rd[0]["id"]
    sa = c.get(f"{R}/clients/{rid}/service-account-user", headers=H).json()
    mgmt = c.get(f"{R}/clients", headers=H, params={"clientId": "realm-management"}).json()[0]
    current = c.get(f"{R}/users/{sa['id']}/role-mappings/clients/{mgmt['id']}", headers=H).json()
    extra = [r for r in current if r["name"] != "view-events"]
    if extra:
        c.request("DELETE", f"{R}/users/{sa['id']}/role-mappings/clients/{mgmt['id']}", headers=H, json=extra)
    if not any(r["name"] == "view-events" for r in current):
        view = c.get(f"{R}/clients/{mgmt['id']}/roles/view-events", headers=H).json()
        c.post(f"{R}/users/{sa['id']}/role-mappings/clients/{mgmt['id']}", headers=H, json=[view])
    names = sorted(r["name"] for r in c.get(f"{R}/users/{sa['id']}/role-mappings/clients/{mgmt['id']}", headers=H).json())
    check(f"{READER} holds only realm-management/view-events", names == ["view-events"], f"roles={names}")

    if not args.no_rotate:
        new = c.post(f"{R}/clients/{rid}/client-secret", headers=H)
        secret = new.json().get("value", "") if new.status_code == 200 else ""
        if not check("audit-reader secret regenerated", bool(secret), f"HTTP {new.status_code}"):
            return 1
        if args.secret_out:
            fd = os.open(args.secret_out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, "w") as f:
                f.write(secret)
            check("secret stored in protected file", True, f"{args.secret_out} (mode 600)")
        if args.secret_arn:
            fd, tmp = tempfile.mkstemp(prefix="kc-reader-")
            try:
                with os.fdopen(fd, "w") as f:
                    f.write(secret)
                os.chmod(tmp, 0o600)
                p = subprocess.run(["aws", "secretsmanager", "put-secret-value", "--secret-id", args.secret_arn,
                                    "--secret-string", f"file://{tmp}"], capture_output=True, text=True, timeout=60)
                check("secret stored in Secrets Manager", p.returncode == 0, f"exit {p.returncode}")
            finally:
                os.unlink(tmp)
    else:
        secret = ""
    if secret:
        rt = c.post(f"/realms/{REALM}/protocol/openid-connect/token",
                    data={"grant_type": "client_credentials", "client_id": READER, "client_secret": secret})
        del secret
        if check("audit reader authenticates (client credentials)", rt.status_code == 200, f"HTTP {rt.status_code}"):
            RH = {"Authorization": f"Bearer {rt.json()['access_token']}"}
            for label, path, want_code in (("read events", "/events", 200), ("list users", "/users", 403),
                                           ("list clients", "/clients", 403)):
                code = c.get(f"{R}{path}", headers=RH).status_code
                check(f"audit reader may {'' if want_code == 200 else 'NOT '}{label}", code == want_code, f"HTTP {code}")

    keys = c.get(f"{R}/keys", headers=H).json().get("keys", [])
    check("realm signing keys exist (generated by this Keycloak, not imported)", any(k.get("use") == "SIG" for k in keys),
          f"{len(keys)} keys")
    return 0 if all(ok for ok, _, _ in results) else 1


if __name__ == "__main__":
    sys.exit(main())
